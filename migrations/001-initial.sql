-- Apply explicitly before deploying; Workers never mutate schema at startup.
CREATE TABLE IF NOT EXISTS public.system_settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT DEFAULT 'admin',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.operation_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT,
  action TEXT,
  entity TEXT,
  entity_id INTEGER,
  payload TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_operation_logs_created ON public.operation_logs(created_at DESC);

CREATE TABLE IF NOT EXISTS public.incidents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  content TEXT,
  status TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'incident',
  start_time INTEGER,
  end_time INTEGER,
  created_at INTEGER DEFAULT (EXTRACT(EPOCH FROM CURRENT_TIMESTAMP)::integer),
  updated_at INTEGER DEFAULT (EXTRACT(EPOCH FROM CURRENT_TIMESTAMP)::integer),
  icon TEXT
);

CREATE TABLE IF NOT EXISTS public.script_guard_blocks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip TEXT,
  location TEXT,
  ua TEXT,
  path TEXT,
  hits INTEGER DEFAULT 0,
  strikes INTEGER DEFAULT 1,
  block_ms INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_script_guard_blocks_created ON public.script_guard_blocks(created_at DESC);

CREATE TABLE IF NOT EXISTS public.script_guard_bans (
  ip TEXT PRIMARY KEY,
  reason TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.apps (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  provider TEXT,
  bg_url TEXT,
  icon_url TEXT,
  download_url TEXT,
  enabled INTEGER DEFAULT 1,
  kind_name TEXT,
  average_rating TEXT,
  original_id TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.seo_url_queue (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT NOT NULL,
  normalized_url TEXT,
  dedupe_key TEXT,
  hits INTEGER DEFAULT 1,
  first_seen TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_seen TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  submit_status TEXT DEFAULT 'pending',
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_seo_queue_last_seen ON public.seo_url_queue(last_seen);
CREATE UNIQUE INDEX IF NOT EXISTS idx_seo_queue_dedupe ON public.seo_url_queue(dedupe_key);

CREATE TABLE IF NOT EXISTS public.seo_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url TEXT NOT NULL,
  queue_id INTEGER,
  channel TEXT,
  status TEXT,
  http_status INTEGER,
  message TEXT,
  batch_size INTEGER,
  key_masked TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_seo_submissions_url_time ON public.seo_submissions(url, created_at);
CREATE INDEX IF NOT EXISTS idx_seo_submissions_created ON public.seo_submissions(created_at);
